def _log_interp(x: np.ndarray, xp: np.ndarray, fp: np.ndarray) -> np.ndarray:
    x = np.asarray(x, dtype=float)
    return np.exp(np.interp(np.log(x), np.log(xp), np.log(fp)))


def be_window_mu_rho(energy_keV: np.ndarray) -> np.ndarray:
    """Mass attenuation (cm^2/g) for Be window."""
    return _log_interp(energy_keV, _BE_WINDOW_DATA[:, 0], _BE_WINDOW_DATA[:, 1])


def ge_components_mu_rho(energy_keV: np.ndarray) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Return (tau, sigma, mu_total) mass attenuation terms for Ge."""
    tau = _log_interp(energy_keV, _GE_COMPONENT_DATA[:, 0], _GE_COMPONENT_DATA[:, 1])
    sigma = _log_interp(energy_keV, _GE_COMPONENT_DATA[:, 0], _GE_COMPONENT_DATA[:, 2])
    mu_total = _log_interp(energy_keV, _GE_COMPONENT_DATA[:, 0], _GE_COMPONENT_DATA[:, 3])
    return tau, sigma, mu_total

